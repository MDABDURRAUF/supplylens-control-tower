_TAG = {"Critical": "#d1495b", "High": "#e9a23b", "Medium": "#3a6ea5", "Low": "#9aa5b1"}


def _money(x) -> str:
    return "n/a" if pd.isna(x) else f"{'-' if x < 0 else ''}${abs(x):,.0f}"


def _pct(x, digits: int = 0) -> str:
    return "n/a" if pd.isna(x) else f"{x:.{digits}%}"


def _kpis(items: list[tuple[str, str]]) -> str:
    return '<div class="kpis">' + "".join(f'<div class="kpi"><b>{escape(v)}</b><span>{escape(k)}</span></div>' for k, v in items) + "</div>"


def _table(df: pd.DataFrame, formats: dict | None = None, empty: str = "Nothing to show.") -> str:
    if df.empty:
        return f'<p class="note">{escape(empty)}</p>'
    formats = formats or {}
    head = "".join(f"<th>{escape(str(c).replace('_', ' '))}</th>" for c in df.columns)
    body = []
    for _, row in df.iterrows():
        cells = []
        for col, val in row.items():
            if col in formats:
                cells.append(f'<td class="num">{escape(formats[col](val))}</td>')
            elif col == "priority":
                cells.append(f'<td><span class="tag" style="background:{_TAG.get(val, "#9aa5b1")}">{escape(str(val))}</span></td>')
            elif isinstance(val, pd.Timestamp):
                cells.append(f"<td>{val:%d %b %Y}</td>")
            else:
                cells.append(f"<td>{escape(str(val))}</td>")
        body.append("<tr>" + "".join(cells) + "</tr>")
    return f'<div class="scroll"><table><thead><tr>{head}</tr></thead><tbody>{"".join(body)}</tbody></table></div>'


def _bars(rows: list[tuple[str, float, str]], color: str, top: float | None = None) -> str:
    top = top or max((abs(v) for _, v, _ in rows), default=0) or 1
    return "".join(
        f'<div class="bar"><span>{escape(label)}</span><div class="track"><div class="fill" style="width:{max(0, v) / top:.1%};'
        f'background:{color}"></div></div><span>{escape(text)}</span></div>'
        for label, v, text in rows
    )


def _page(title: str, subtitle: str, body: str) -> str:
    return (
        '<!doctype html><html lang="en"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width,initial-scale=1">'
        f"<title>{escape(title)}</title><style>{_CSS}</style></head><body><main>"
        f'<h1>{escape(title)}</h1><p class="note">{escape(subtitle)}</p>{body}'
        '<p class="note" style="margin-top:40px">Generated by SupplyLens Control Tower from simulated data. '
        "Not real company data.</p></main></body></html>"
    )


def briefing_headline(board: pd.DataFrame, recs: pd.DataFrame, counts: dict) -> str:
    """One paragraph saying what matters today."""
    if board.empty:
        return "There are no open orders today."
    urgent = int(board["priority"].isin(["Critical", "High"]).sum())
    text = (f"{len(board)} orders are open with {_money(board['value_at_risk'].sum())} at risk; "
            f"{urgent} {'is' if urgent == 1 else 'are'} high or critical priority.")
    if len(recs):
        text += (f" {len(recs)} order{'' if len(recs) == 1 else 's'} {'has' if len(recs) == 1 else 'have'} a response that "
                 f"beats the current plan, worth an estimated {_money(recs['expected_saving'].sum())}.")
    else:
        text += " No response currently beats keeping the open orders as planned."
    if counts.get("overdue"):
        text += f" {counts['overdue']} action{'' if counts['overdue'] == 1 else 's'} {'is' if counts['overdue'] == 1 else 'are'} overdue."
    return text


def build_briefing(as_of, board: pd.DataFrame, recs: pd.DataFrame, actions: pd.DataFrame, counts: dict, news: dict,
                   results: dict) -> str:
    """The daily briefing as an HTML page.

    ``recs`` comes from ``briefing.recommendations``, ``counts`` from
    ``pipeline_counts``, ``news`` from ``whats_new`` and ``results`` from
    ``results_to_date``.
    """
    as_of = pd.Timestamp(as_of)
    body = f'<p class="lead">{escape(briefing_headline(board, recs, counts))}</p>'
    body += _kpis([
        ("open orders", f"{len(board)}"),
        ("value at risk", _money(board["value_at_risk"].sum() if len(board) else 0)),
        ("need attention", f"{counts['needs_attention']}"),
        ("awaiting decision", f"{counts['awaiting_decision']}"),
        ("actions overdue", f"{counts['overdue']}"),
        ("awaiting outcome", f"{counts['awaiting_outcome']}"),
    ])

    body += "<h2>Recommended responses</h2>"
    body += '<p class="note">Orders where a response is cheaper in expected cost and no riskier than the plan, highest value at risk first.</p>'
    cols = ["order_id", "priority", "vendor", "sku", "recommendation", "expected_saving", "risk_before", "risk_after", "main_reason"]
    body += _table(recs[cols] if len(recs) else recs,
                   {"expected_saving": _money, "risk_before": _pct, "risk_after": _pct},
                   "No response currently beats the plan for any open order.")

    body += "<h2>Highest-risk open orders</h2>"
    top = board.head(10)[["order_id", "priority", "stage", "days_to_due", "vendor", "sku", "goods_value", "late_probability",
                          "stockout_probability", "value_at_risk"]] if len(board) else board
    body += _table(top, {"goods_value": _money, "late_probability": _pct, "stockout_probability": _pct,
                         "value_at_risk": _money, "days_to_due": lambda d: f"{d:+d}"})

    body += "<h2>Actions due or overdue</h2>"
    due = actions[actions["status"].isin(["open", "in progress"]) & (actions["due_date"] <= as_of)] if len(actions) else actions
    body += _table(due[["action_id", "order_id", "option", "owner", "due_date", "decision", "status"]] if len(due) else due,
                   empty="No actions are due today.")

    body += "<h2>Since yesterday</h2>"
    body += _kpis([("orders placed", f"{news['orders_placed']}"), ("value placed", _money(news["value_placed"])),
                   ("deliveries received", f"{news['deliveries']}"), ("of which late", f"{news['late_deliveries']}")])

    body += "<h2>Results to date</h2>"
    if results["outcomes"]:
        body += _kpis([
            ("outcomes recorded", f"{results['outcomes']}"), ("recommendations adopted", f"{results['adopted']}"),
            ("estimated saving", _money(results["estimated_saving"])), ("realized saving", _money(results["realized_saving"])),
            ("late deliveries avoided", f"{results['late_deliveries_avoided']}"),
            ("on time when adopted", _pct(results["on_time_adopted"])),
        ])
        body += ('<p class="caveat">Estimated saving is what the model expected at decision time. Realized saving compares each '
                 "order with its simulated baseline and can only be measured because the data is simulated.</p>")
    else:
        body += '<p class="note">No outcomes have been recorded yet.</p>'
    return _page(f"Daily briefing: {as_of:%A %d %B %Y}", "SupplyLens Control Tower", body)


def build_performance_report(replay: pd.DataFrame, title: str = "Policy performance against the baseline") -> str:
    """The policy replay as an HTML report: headline, comparison table, breakdown and caveats."""
    s = summarize_replay(replay)
    by = replay_by_option(replay)
    start, end = replay["decided_on"].min(), replay["decided_on"].max()
    ratio = s["estimate_ratio"]
    verdict = ("the model over-promised" if ratio < 0.9 else "the estimates held up" if ratio <= 1.1 else "the model under-estimated the benefit")
    lead = (
        f"Following the recommendations on {s['orders']:,} orders changed {s['share_changed']:.0%} of them, cut total cost by "
        f"{_money(s['realized_saving'])} ({s['realized_saving_pct']:.2%}) and moved on-time delivery from "
        f"{s['baseline_on_time']:.1%} to {s['policy_on_time']:.1%}. For every $1 of estimated saving, ${ratio:,.2f} was realized: {verdict}."
    )
    body = f'<p class="lead">{escape(lead)}</p>'
    body += _kpis([
        ("orders decided", f"{s['orders']:,}"), ("orders changed", f"{s['orders_changed']:,}"),
        ("estimated saving", _money(s["estimated_saving"])), ("realized saving", _money(s["realized_saving"])),
        ("on time, baseline", _pct(s["baseline_on_time"], 1)), ("on time, policy", _pct(s["policy_on_time"], 1)),
    ])

    body += "<h2>Baseline against policy</h2>"
    compare = pd.DataFrame(
        {
            "measure": ["Total cost", "On-time delivery (by value)", "Orders changed"],
            "baseline": [_money(s["baseline_cost"]), _pct(s["baseline_on_time"], 1), "0"],
            "policy": [_money(s["policy_cost"]), _pct(s["policy_on_time"], 1), f"{s['orders_changed']:,}"],
            "difference": [_money(s["policy_cost"] - s["baseline_cost"]),
                           f"{(s['policy_on_time'] - s['baseline_on_time']) * 100:+.1f} pts", f"{s['orders_changed']:,}"],
        }
    )
    body += _table(compare)

    changed = by[by["kind"] != "keep"]
    body += "<h2>Saving by type of change</h2><p class=\"note\">Estimated (grey) against realized (green).</p>"
    scale = max(changed["estimated_saving"].abs().max(), changed["realized_saving"].abs().max()) if len(changed) else 1
    for _, r in changed.iterrows():
        body += (f"<p style=\"margin:14px 0 2px\"><b>{escape(str(r['kind']))}</b> — {int(r['orders'])} orders</p>"
                 + _bars([("estimated", r["estimated_saving"], _money(r["estimated_saving"]))], "#9aa5b1", scale)
                 + _bars([("realized", r["realized_saving"], _money(r["realized_saving"]))], "#2a9d8f", scale))
    body += _table(by, {"estimated_saving": _money, "realized_saving": _money, "est_risk_before": _pct, "est_risk_after": _pct,
                        "late_share_baseline": _pct, "late_share_policy": _pct})

    body += "<h2>How to read this</h2>"
    body += ('<p class="caveat"><b>Estimated</b> saving is what the model expected at decision time. <b>Realized</b> saving is the '
             "baseline cost minus the policy cost for the same orders, each played out in the simulated world with the same "
             "random luck. That comparison is possible only in a simulation. With real orders the baseline outcome of a changed "
             "order is never observed, so demonstrating savings would require a controlled comparison, such as keeping a random "
             "share of orders on the original plan. Each decision is evaluated independently; supplier capacity is not modelled.</p>")
    return _page(title, f"Replay of {start:%d %b %Y} to {end:%d %b %Y}, decided weekly", body)


def write_html(html: str, path: str | Path) -> Path:
    path = Path(path)
    path.write_text(html, encoding="utf-8")
    return path
